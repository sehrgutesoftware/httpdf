package pdf

import (
	"bytes"
	"encoding/binary"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"slices"
	"strconv"
)

// errUnstamped is returned by creatorStamper.Close when the PDF doesn't have
// the expected structure. The PDF has been passed through unmodified then.
var errUnstamped = errors.New("creator not stamped")

const (
	// maxHeadSize limits how much of the PDF's start is retained to find the
	// document information dictionary, which Skia writes as the first object.
	maxHeadSize = 64 << 10
	// tailSize is how much of the PDF's end is retained to find the trailer.
	tailSize = 1 << 10
)

// creatorStamper writes a PDF generated by Chromium (Skia) through to dst and,
// on Close, appends an incremental update that prefixes the Creator in the
// document information dictionary.
type creatorStamper struct {
	dst    io.Writer
	prefix string
	err    error
	n      int64
	head   []byte
	tail   []byte
}

// newCreatorStamper creates a creatorStamper. The prefix must be printable
// ASCII and is separated from the original Creator by a space.
func newCreatorStamper(dst io.Writer, prefix string) *creatorStamper {
	return &creatorStamper{dst: dst, prefix: prefix}
}

// Write writes p to the underlying writer.
func (s *creatorStamper) Write(p []byte) (int, error) {
	if s.err != nil {
		return 0, s.err
	}
	n, err := s.dst.Write(p)
	s.record(p[:n])
	if err != nil {
		s.err = err
	}
	return n, err
}

// Close appends the incremental update. If the PDF doesn't have the expected
// structure, nothing is appended and an error wrapping errUnstamped is
// returned.
func (s *creatorStamper) Close() error {
	if s.err != nil {
		return s.err
	}
	update, err := s.update()
	if err != nil {
		return fmt.Errorf("%w: %w", errUnstamped, err)
	}
	_, err = s.dst.Write(update)
	return err
}

// record retains the start and the end of the PDF
func (s *creatorStamper) record(p []byte) {
	s.n += int64(len(p))

	if room := maxHeadSize - len(s.head); room > 0 {
		s.head = append(s.head, p[:min(room, len(p))]...)
	}

	if len(p) >= tailSize {
		s.tail = append(s.tail[:0], p[len(p)-tailSize:]...)
		return
	}
	s.tail = append(s.tail, p...)
	if len(s.tail) > 2*tailSize {
		n := copy(s.tail, s.tail[len(s.tail)-tailSize:])
		s.tail = s.tail[:n]
	}
}

// update builds the incremental update, which redefines the document
// information dictionary, see PDF 32000-1:2008, section 7.5.6.
func (s *creatorStamper) update() ([]byte, error) {
	if !isPrintableASCII(s.prefix) {
		return nil, fmt.Errorf("prefix %q is not printable ASCII", s.prefix)
	}

	num, gen, info, err := parseFirstObject(s.head)
	if err != nil {
		return nil, err
	}
	trailer, startxref, err := parseTrailer(s.tail)
	if err != nil {
		return nil, err
	}

	infoRef, ok := lookup(trailer, "/Info")
	if !ok {
		return nil, errors.New("trailer has no /Info")
	}
	infoNum, infoGen, err := parseRef(infoRef)
	if err != nil {
		return nil, fmt.Errorf("trailer /Info: %w", err)
	}
	if infoNum != num || infoGen != gen {
		return nil, fmt.Errorf("trailer /Info is %d %d R, but the first object is %d %d", infoNum, infoGen, num, gen)
	}
	if gen > 65535 {
		return nil, fmt.Errorf("generation number %d is out of range", gen)
	}
	if _, ok := lookup(trailer, "/Prev"); ok {
		return nil, errors.New("PDF has been updated before")
	}
	if startxref >= s.n {
		return nil, fmt.Errorf("startxref %d is beyond the end of the PDF", startxref)
	}

	info, err = prefixCreator(info, s.prefix)
	if err != nil {
		return nil, err
	}
	trailer = append(trailer, entry{key: []byte("/Prev"), value: strconv.AppendInt(nil, startxref, 10)})

	var b bytes.Buffer
	if !bytes.HasSuffix(s.tail, []byte("\n")) && !bytes.HasSuffix(s.tail, []byte("\r")) {
		b.WriteByte('\n')
	}
	objOffset := s.n + int64(b.Len())
	fmt.Fprintf(&b, "%d %d obj\n", num, gen)
	writeDict(&b, info)
	b.WriteString("\nendobj\n")

	xrefOffset := s.n + int64(b.Len())
	fmt.Fprintf(&b, "xref\n%d 1\n%010d %05d n \n", num, objOffset, gen)
	b.WriteString("trailer\n")
	writeDict(&b, trailer)
	fmt.Fprintf(&b, "\nstartxref\n%d\n%%%%EOF\n", xrefOffset)

	return b.Bytes(), nil
}

// prefixCreator prefixes the /Creator in the given dictionary entries, or
// adds it if there's none.
func prefixCreator(info []entry, prefix string) ([]entry, error) {
	info = slices.Clone(info)
	for i, e := range info {
		if string(e.key) != "/Creator" {
			continue
		}
		creator, err := stringBytes(e.value)
		if err != nil {
			return nil, fmt.Errorf("/Creator: %w", err)
		}
		info[i].value = encodeString(prefixText(creator, prefix))
		return info, nil
	}
	return append(info, entry{key: []byte("/Creator"), value: encodeString([]byte(prefix))}), nil
}

// parseFirstObject parses the PDF's first object, which must be a dictionary
func parseFirstObject(head []byte) (num, gen int64, dict []entry, err error) {
	if !bytes.HasPrefix(head, []byte("%PDF-")) {
		return 0, 0, nil, errors.New("missing PDF header")
	}

	s := &scanner{b: head}
	s.skipComments()
	num, err = s.integer()
	if err == nil {
		gen, err = s.integer()
	}
	if err == nil {
		err = s.keyword("obj")
	}
	if err == nil {
		dict, err = s.dict(0)
	}
	if err == nil {
		err = s.keyword("endobj")
	}

	if errors.Is(err, errUnexpectedEnd) && len(head) == maxHeadSize {
		return 0, 0, nil, fmt.Errorf("first object exceeds %d bytes", maxHeadSize)
	} else if err != nil {
		return 0, 0, nil, fmt.Errorf("first object: %w", err)
	}
	return num, gen, dict, nil
}

// parseTrailer parses the last trailer dictionary and startxref value, which
// must be at the very end of the given data
func parseTrailer(tail []byte) (dict []entry, startxref int64, err error) {
	i := bytes.LastIndex(tail, []byte("trailer"))
	if i < 0 {
		return nil, 0, errors.New("no trailer found")
	}

	s := &scanner{b: tail[i+len("trailer"):]}
	dict, err = s.dict(0)
	if err == nil {
		err = s.keyword("startxref")
	}
	if err == nil {
		startxref, err = s.integer()
	}
	if err != nil {
		return nil, 0, fmt.Errorf("trailer: %w", err)
	}

	if rest := bytes.TrimSpace(s.b[s.pos:]); !bytes.Equal(rest, []byte("%%EOF")) {
		return nil, 0, errors.New("trailer: missing %%EOF at the end")
	}
	return dict, startxref, nil
}

// parseRef parses an indirect reference, such as "12 0 R"
func parseRef(raw []byte) (num, gen int64, err error) {
	s := &scanner{b: raw}
	num, err = s.integer()
	if err == nil {
		gen, err = s.integer()
	}
	if err == nil {
		err = s.keyword("R")
	}
	if err == nil {
		s.skipSpace()
		if s.pos != len(s.b) {
			err = fmt.Errorf("not a reference: %q", raw)
		}
	}
	return num, gen, err
}

// entry is a key-value pair of a dictionary. Both are raw PDF syntax.
type entry struct {
	key, value []byte
}

func lookup(dict []entry, key string) ([]byte, bool) {
	for _, e := range dict {
		if string(e.key) == key {
			return e.value, true
		}
	}
	return nil, false
}

// writeDict writes the dictionary in the same layout Skia uses
func writeDict(b *bytes.Buffer, dict []entry) {
	b.WriteString("<<")
	for i, e := range dict {
		if i > 0 {
			b.WriteByte('\n')
		}
		b.Write(e.key)
		b.WriteByte(' ')
		b.Write(e.value)
	}
	b.WriteString(">>")
}

var errUnexpectedEnd = errors.New("unexpected end of data")

// maxNesting limits the nesting of arrays and dictionaries
const maxNesting = 32

// scanner scans the subset of PDF syntax that occurs in Skia's document
// information and trailer dictionaries, see PDF 32000-1:2008, section 7.2-7.3.
// It returns the raw bytes of objects, so they can be copied verbatim.
type scanner struct {
	b   []byte
	pos int
}

func isWhitespace(c byte) bool {
	switch c {
	case 0, '\t', '\n', '\f', '\r', ' ':
		return true
	}
	return false
}

func isDelimiter(c byte) bool {
	switch c {
	case '(', ')', '<', '>', '[', ']', '{', '}', '/', '%':
		return true
	}
	return false
}

func (s *scanner) skipSpace() {
	for s.pos < len(s.b) && isWhitespace(s.b[s.pos]) {
		s.pos++
	}
}

// skipComments skips whitespace and comments, such as the PDF header
func (s *scanner) skipComments() {
	for {
		s.skipSpace()
		if s.pos >= len(s.b) || s.b[s.pos] != '%' {
			return
		}
		i := bytes.IndexAny(s.b[s.pos:], "\r\n")
		if i < 0 {
			s.pos = len(s.b)
			return
		}
		s.pos += i
	}
}

// consume advances past token if it's next
func (s *scanner) consume(token string) bool {
	if bytes.HasPrefix(s.b[s.pos:], []byte(token)) {
		s.pos += len(token)
		return true
	}
	return false
}

// regular returns the next run of regular characters, such as a number or a
// keyword
func (s *scanner) regular() []byte {
	s.skipSpace()
	start := s.pos
	for s.pos < len(s.b) && !isWhitespace(s.b[s.pos]) && !isDelimiter(s.b[s.pos]) {
		s.pos++
	}
	return s.b[start:s.pos]
}

func (s *scanner) keyword(keyword string) error {
	if token := s.regular(); string(token) != keyword {
		if len(token) == 0 && s.pos == len(s.b) {
			return errUnexpectedEnd
		}
		return fmt.Errorf("expected %q, got %q", keyword, token)
	}
	return nil
}

// integer scans a non-negative integer
func (s *scanner) integer() (int64, error) {
	token := s.regular()
	if len(token) == 0 && s.pos == len(s.b) {
		return 0, errUnexpectedEnd
	}
	n, err := strconv.ParseUint(string(token), 10, 63)
	if err != nil {
		return 0, fmt.Errorf("expected an integer, got %q", token)
	}
	return int64(n), nil
}

// object scans the next object and returns its raw bytes. An indirect
// reference, such as "12 0 R", is returned as one object.
func (s *scanner) object(depth int) ([]byte, error) {
	if depth > maxNesting {
		return nil, errors.New("objects nested too deeply")
	}
	s.skipSpace()
	if s.pos >= len(s.b) {
		return nil, errUnexpectedEnd
	}

	start := s.pos
	var err error
	switch c := s.b[s.pos]; {
	case c == '(':
		err = s.literalString()
	case c == '<' && s.pos+1 < len(s.b) && s.b[s.pos+1] == '<':
		_, err = s.dict(depth + 1)
	case c == '<':
		err = s.hexString()
	case c == '[':
		err = s.array(depth + 1)
	case c == '/':
		s.pos++
		s.regular()
	case isDelimiter(c):
		err = fmt.Errorf("unexpected %q", c)
	default:
		token := s.regular()
		if isDigits(token) {
			afterNum := s.pos
			if gen := s.regular(); !isDigits(gen) || string(s.regular()) != "R" {
				s.pos = afterNum
			}
		}
	}
	if err != nil {
		return nil, err
	}
	return s.b[start:s.pos], nil
}

// dict scans a dictionary and returns its entries
func (s *scanner) dict(depth int) ([]entry, error) {
	s.skipSpace()
	if !s.consume("<<") {
		if s.pos == len(s.b) {
			return nil, errUnexpectedEnd
		}
		return nil, errors.New("expected a dictionary")
	}
	var dict []entry
	for {
		s.skipSpace()
		if s.consume(">>") {
			return dict, nil
		}
		if s.pos == len(s.b) {
			return nil, errUnexpectedEnd
		}
		if s.b[s.pos] != '/' {
			return nil, errors.New("expected a name as dictionary key")
		}
		key, err := s.object(depth)
		if err != nil {
			return nil, err
		}
		value, err := s.object(depth)
		if err != nil {
			return nil, err
		}
		dict = append(dict, entry{key: key, value: value})
	}
}

func (s *scanner) array(depth int) error {
	s.pos++ // [
	for {
		s.skipSpace()
		if s.consume("]") {
			return nil
		}
		if _, err := s.object(depth); err != nil {
			return err
		}
	}
}

func (s *scanner) literalString() error {
	s.pos++ // (
	for nesting := 1; s.pos < len(s.b); s.pos++ {
		switch s.b[s.pos] {
		case '\\':
			s.pos++
		case '(':
			nesting++
		case ')':
			if nesting--; nesting == 0 {
				s.pos++
				return nil
			}
		}
	}
	s.pos = len(s.b)
	return errUnexpectedEnd
}

func (s *scanner) hexString() error {
	end := bytes.IndexByte(s.b[s.pos:], '>')
	if end < 0 {
		return errUnexpectedEnd
	}
	end += s.pos
	if _, err := decodeHex(s.b[s.pos+1 : end]); err != nil {
		return err
	}
	s.pos = end + 1
	return nil
}

func isDigits(b []byte) bool {
	if len(b) == 0 {
		return false
	}
	for _, c := range b {
		if c < '0' || c > '9' {
			return false
		}
	}
	return true
}

func isPrintableASCII(s string) bool {
	if s == "" {
		return false
	}
	for i := range len(s) {
		if s[i] < ' ' || s[i] > '~' {
			return false
		}
	}
	return true
}

var (
	utf16BOM = []byte{0xFE, 0xFF}
	utf8BOM  = []byte{0xEF, 0xBB, 0xBF}
)

// prefixText prepends prefix and a space to the text string s, keeping its
// encoding. The prefix must be printable ASCII, which is the same in
// PDFDocEncoding and UTF-8.
func prefixText(s []byte, prefix string) []byte {
	p := prefix + " "
	switch {
	case bytes.HasPrefix(s, utf16BOM):
		out := slices.Clone(utf16BOM)
		for i := range len(p) {
			out = binary.BigEndian.AppendUint16(out, uint16(p[i]))
		}
		return append(out, s[len(utf16BOM):]...)
	case bytes.HasPrefix(s, utf8BOM):
		return slices.Concat(utf8BOM, []byte(p), s[len(utf8BOM):])
	default:
		return slices.Concat([]byte(p), s)
	}
}

// stringBytes returns the bytes of a raw literal or hexadecimal string object
func stringBytes(raw []byte) ([]byte, error) {
	switch {
	case len(raw) >= 2 && raw[0] == '(' && raw[len(raw)-1] == ')':
		return unescapeLiteral(raw[1 : len(raw)-1]), nil
	case len(raw) >= 2 && raw[0] == '<' && raw[len(raw)-1] == '>':
		return decodeHex(raw[1 : len(raw)-1])
	}
	return nil, fmt.Errorf("not a string: %q", raw)
}

// unescapeLiteral decodes the contents of a literal string, see PDF
// 32000-1:2008, section 7.3.4.2
func unescapeLiteral(b []byte) []byte {
	out := make([]byte, 0, len(b))
	for i := 0; i < len(b); i++ {
		c := b[i]
		if c == '\r' {
			// An unescaped end-of-line marker is read as \n
			if i+1 < len(b) && b[i+1] == '\n' {
				i++
			}
			out = append(out, '\n')
			continue
		}
		if c != '\\' || i+1 == len(b) {
			out = append(out, c)
			continue
		}

		i++
		switch c = b[i]; c {
		case 'n':
			out = append(out, '\n')
		case 'r':
			out = append(out, '\r')
		case 't':
			out = append(out, '\t')
		case 'b':
			out = append(out, '\b')
		case 'f':
			out = append(out, '\f')
		case '\r':
			// A backslash at the end of a line continues the string
			if i+1 < len(b) && b[i+1] == '\n' {
				i++
			}
		case '\n':
		case '0', '1', '2', '3', '4', '5', '6', '7':
			v := int(c - '0')
			for range 2 {
				if i+1 >= len(b) || b[i+1] < '0' || b[i+1] > '7' {
					break
				}
				i++
				v = v*8 + int(b[i]-'0')
			}
			out = append(out, byte(v))
		default:
			// Includes \(, \) and \\. For unknown escapes, the backslash is
			// ignored.
			out = append(out, c)
		}
	}
	return out
}

// decodeHex decodes the contents of a hexadecimal string, see PDF
// 32000-1:2008, section 7.3.4.3
func decodeHex(b []byte) ([]byte, error) {
	digits := make([]byte, 0, len(b)+1)
	for _, c := range b {
		if !isWhitespace(c) {
			digits = append(digits, c)
		}
	}
	if len(digits)%2 == 1 {
		digits = append(digits, '0')
	}
	out := make([]byte, len(digits)/2)
	if _, err := hex.Decode(out, digits); err != nil {
		return nil, fmt.Errorf("hexadecimal string: %w", err)
	}
	return out, nil
}

// encodeString encodes b as a string object. Like Skia, UTF-16 text is
// encoded as a hexadecimal string, and anything else as a literal string.
func encodeString(b []byte) []byte {
	if bytes.HasPrefix(b, utf16BOM) {
		out := make([]byte, 0, 2*len(b)+2)
		out = append(out, '<')
		out = append(out, bytes.ToUpper(hex.AppendEncode(nil, b))...)
		return append(out, '>')
	}

	out := make([]byte, 0, len(b)+2)
	out = append(out, '(')
	for _, c := range b {
		switch {
		case c == '\\' || c == '(' || c == ')':
			out = append(out, '\\', c)
		case c < ' ' || c > '~':
			out = fmt.Appendf(out, "\\%03o", c)
		default:
			out = append(out, c)
		}
	}
	return append(out, ')')
}
